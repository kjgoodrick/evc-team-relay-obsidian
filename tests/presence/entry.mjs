import * as Y from 'yjs';
import { Awareness } from 'y-protocols/awareness';
import { flushSync } from 'svelte';
import { mountComponent } from '../../src/svelteMount.ts';
import CollaboratorAwareness from '../../src/components/CollaboratorAwareness.svelte';
window.activeDocument=document;
const doc=new Y.Doc(), awareness=new Awareness(doc), results=[], errors=[];
const url=location.origin+'/avatar.svg';
const me={id:'alice',name:'Alice Example',color:'#167647',avatarUrl:url};
awareness.setLocalStateField('user',me);
for(let n=1;n<=6;n++)awareness.states.set(n,{user:{id:'peer'+n,name:n===1?'Bob With A Very Long Display Name That Must Fit':'Peer '+n,color:'#6952cc',...(n%2===0?{avatarUrl:url}:{} )}});
const root=document.querySelector('#mount');
const otherDoc=new Y.Doc(), otherAwareness=new Awareness(otherDoc);
otherAwareness.setLocalStateField('user',{...me,color:'#0000ff'});
for(let n=1;n<=6;n++)otherAwareness.states.set(n,{user:{...awareness.states.get(n).user,color:'#ff0000'}});
const otherRoot=document.querySelector('#mount-second');
const otherComponent=mountComponent(CollaboratorAwareness,{target:otherRoot,props:{collabAwareness:otherAwareness}});
const component=mountComponent(CollaboratorAwareness,{target:document.querySelector('#mount'),props:{collabAwareness:awareness}});
let saving=Promise.resolve();
const save=()=>{const data={viewport:[innerWidth,innerHeight],dark:matchMedia('(prefers-color-scheme:dark)').matches,results,errors,images:[...document.querySelectorAll('img')].map(i=>({src:i.getAttribute('src'),width:i.naturalWidth,complete:i.complete,classes:i.className,referrer:i.referrerPolicy})),userAgent:navigator.userAgent};localStorage.setItem('presence-results',JSON.stringify(data));const body=JSON.stringify(data);saving=saving.then(()=>fetch('/results',{method:'POST',headers:{'Content-Type':'application/json'},body})).catch(()=>{});};
const capture=e=>{if(e.message||e.reason){errors.push(String(e.message||e.reason));document.querySelector('#errors').textContent=errors.join('\n');save();}};
window.addEventListener('error',capture);window.addEventListener('unhandledrejection',capture);
const viewport=()=>document.querySelector('#viewport').textContent=innerWidth+' × '+innerHeight+' / '+(matchMedia('(prefers-color-scheme:dark)').matches?'dark':'light');window.addEventListener('resize',viewport);viewport();
const report=s=>{results.push(s);document.querySelector('#results').textContent=results.join('\n');save();};
const assert=(v,s)=>{if(!v)throw Error(s);report('PASS '+s);};
const settle=()=>new Promise(r=>setTimeout(r,150));
const update=picture=>{awareness.setLocalStateField('user',{...me,avatarUrl:picture});flushSync();};
document.querySelector('#refresh').onclick=()=>{update(url+'?changed=1');report('Picture updated live');};
document.querySelector('#remove').onclick=()=>{update(undefined);report('Initial restored');};
document.querySelector('#checks').onclick=async()=>{try{
results.length=0;errors.length=0;document.querySelector('#errors').textContent='';update(url);await settle();
assert(root.querySelectorAll('.evc-stacked-avatar').length===4,'stack capped at four');
assert(root.querySelector('.evc-more-indicator').textContent.trim()==='+3','overflow count');
const bordersMatch=()=>[...root.querySelectorAll('.evc-stacked-avatar')].every(el=>el.querySelector('.evc-avatar-with-border').style.borderColor===otherRoot.querySelector('.evc-stacked-avatar[aria-label='+JSON.stringify(el.getAttribute('aria-label'))+'] .evc-avatar-with-border').style.borderColor);
assert(bordersMatch(),'same people keep the same borders in two notes despite older peer colors');
assert([...document.querySelectorAll('img')].every(i=>i.naturalWidth>0&&i.classList.contains('evc-picture-loaded')),'real images loaded');
assert([...document.querySelectorAll('img')].every(i=>i.referrerPolicy==='no-referrer'),'no image referrer');
root.querySelector('.evc-avatar-stack').click();flushSync();
assert(root.querySelectorAll('.evc-user-item').length===7,'popover lists all users');
assert(root.querySelector('.evc-user-popover img')?.naturalWidth>0||await settle().then(()=>root.querySelector('.evc-user-popover img')?.naturalWidth>0),'popover picture loaded');
update(location.origin+'/missing.png');await settle();
assert(!root.querySelector('.evc-stacked-avatar[aria-label="Alice Example"] img'),'failed picture falls back');
update(url+'?new=2');await settle();
assert(root.querySelector('.evc-stacked-avatar[aria-label="Alice Example"] img')?.naturalWidth>0,'new URL retries after failure');
update(undefined);assert(!root.querySelector('.evc-stacked-avatar[aria-label="Alice Example"] img'),'removed picture falls back');
update('file:///private/secret.png');assert(!root.querySelector('.evc-stacked-avatar[aria-label="Alice Example"] img'),'file URLs rejected');
update(url);await settle();
assert(bordersMatch(),'picture changes and failures preserve identity colors');
assert(document.documentElement.scrollWidth<=innerWidth,'no horizontal page overflow');
assert(errors.length===0,'no runtime errors');
report('Completed '+innerWidth+'×'+innerHeight);localStorage.setItem('presence-results',JSON.stringify({viewport:[innerWidth,innerHeight],results,errors,userAgent:navigator.userAgent}));
}catch(e){capture({reason:e});}};
window.presenceFixture={awareness,component,otherAwareness,otherComponent,results,errors};
